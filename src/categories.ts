export const CATEGORY_MAP = Object.fromEntries(CATEGORIES.map(c => [c.id, c])) as Record<CategoryId, Category>;

export function detectCategory(text: string): CategoryId {
  const lower = text.toLowerCase();
  for (const cat of CATEGORIES) {
    if (cat.id === 'other') continue;
    if (cat.keywords.some(kw => lower.includes(kw))) return cat.id;
  }
  return 'other';
}
